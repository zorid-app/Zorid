import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {defineConfig} from 'vite';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const {createCoreWasmAssets}=require('./scripts/core-wasm-assets-plugin.cjs');
const {createPdfAssets}=require('./scripts/pdf-assets.cjs');
const {createMathAssets}=require('./scripts/math-assets.cjs');
const {createPrismAssets}=require('./scripts/prism-assets.cjs');
const {buildCoreWasm,sourceInputs}=require('./scripts/build-core-wasm.cjs');

const root=fileURLToPath(new URL('.',import.meta.url));
/** Preserve upstream and generated bytes; these runtime modules must not be bundled. */
export function runtimeAssets(assets,{core=false}={}) {
  return {
    name:'zorid-runtime-assets',
    configResolved(config){if(core&&config.build.watch)throw Error('Rust/WASM watch builds require the Vite dev server; use pnpm dev.');},
    async buildStart(){
      if(core)for(const name of await sourceInputs(root))this.addWatchFile(path.join(root,name));
    },
    generateBundle(){for(const [fileName,source] of assets)this.emitFile({type:'asset',fileName,source});},
    async configureServer(server){
      // Only exact collected asset names are served; no arbitrary filesystem path mapping.
      server.middlewares.use((req,res,next)=>{
        let name;try{name=decodeURIComponent(new URL(req.url,'http://localhost').pathname).replace(/^\//,'');}catch{return next();}
        const data=assets.get(name);if(!data)return next();
        if(!['GET','HEAD'].includes(req.method)){res.statusCode=405;res.setHeader('Allow','GET, HEAD');return res.end();}
        const mime={'.wasm':'application/wasm','.js':'text/javascript','.mjs':'text/javascript','.css':'text/css','.json':'application/json','.svg':'image/svg+xml','.png':'image/png','.gif':'image/gif','.woff':'font/woff','.woff2':'font/woff2','.ttf':'font/ttf','.icc':'application/vnd.iccprofile'};
        res.setHeader('Content-Type',mime[path.extname(name)]||'application/octet-stream');
        res.setHeader('Cache-Control','no-cache');res.end(req.method==='HEAD'?undefined:data);
      });
      if(core){
        // Reconfiguration regenerates the content-addressed module define together with its assets.
        {
          const names=await sourceInputs(root);
          const inputs=new Set(names.map(name=>path.join(root,name)));
          const crates=path.join(root,'crates')+path.sep;
          server.watcher.add([...inputs,path.join(root,'crates')]);
          let restarting=false;
          const restart=file=>{
            const isRust=file.startsWith(crates)&&(file.endsWith('.rs')||path.basename(file)==='Cargo.toml');
            if(!restarting&&(inputs.has(file)||isRust)){restarting=true;void server.restart();}
          };
          server.watcher.on('change',restart).on('add',restart).on('unlink',restart);
        }
      }
    },
  };
}
export default defineConfig(async({mode})=>{
  const native=mode==='native';
  const fixture=!native&&process.env.ZORID_CORE_FIXTURES==='1';
  const buildId=fixture?process.env.ZORID_CORE_BUILD_ID||'':'';
  const supplied=fixture?process.env.ZORID_CORE_WASM_DIR:undefined;
  if(fixture&&(!supplied||!path.isAbsolute(supplied)))throw Error('Core fixture builds require an absolute ZORID_CORE_WASM_DIR');
  const directory=native?undefined:fixture?supplied:await buildCoreWasm({root});
  const core=await createCoreWasmAssets({enabled:!native,fixture,directory,buildId:buildId||undefined});
  const assets=new Map(core);
  for(const collect of [createPdfAssets,createMathAssets,createPrismAssets])for(const [name,bytes] of await collect()){
    if(assets.has(name))throw Error(`Duplicate runtime asset: ${name}`);assets.set(name,bytes);
  }
  return {
    root,base:'./',publicDir:false,
    define:{__ZORID_CORE_FIXTURES__:JSON.stringify(fixture),__ZORID_CORE_BUILD_ID__:JSON.stringify(buildId),__ZORID_CORE_MODULE_PATH__:JSON.stringify(core.modulePath||'')},
    plugins:[runtimeAssets(assets,{core:!native&&!fixture})],
    server:{host:'127.0.0.1',port:5173,strictPort:true},
    preview:{host:'127.0.0.1',port:4173,strictPort:true},
    // Native WebKit and Electron load relative chunks from dist/index.html.
    build:{target:'es2022',outDir:'dist',emptyOutDir:true,sourcemap:true},
    worker:{format:'iife'},
  };
});
